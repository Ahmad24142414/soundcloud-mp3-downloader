# List of supported language codes
SUPPORTED_LANGUAGES = list(TRANSLATIONS.keys())

# Default language
DEFAULT_LANGUAGE = 'en'


def get_translation(lang_code, key, default=None):
    """
    Get a translation for a specific key in the given language.
    Falls back to English if the translation is not found.
    
    Args:
        lang_code: Language code (e.g., 'en', 'es', 'fr')
        key: Translation key
        default: Default value if key not found
        
    Returns:
        str: Translated string
    """
    if lang_code not in TRANSLATIONS:
        lang_code = DEFAULT_LANGUAGE
    
    translation = TRANSLATIONS.get(lang_code, {}).get(key)
    
    if translation is None:
        # Fallback to English
        translation = TRANSLATIONS.get(DEFAULT_LANGUAGE, {}).get(key, default or key)
    
    return translation


def get_all_translations(lang_code):
    """
    Get all translations for a specific language.
    
    Args:
        lang_code: Language code
        
    Returns:
        dict: All translations for the language
    """
    if lang_code not in TRANSLATIONS:
        lang_code = DEFAULT_LANGUAGE
    
    return TRANSLATIONS.get(lang_code, TRANSLATIONS[DEFAULT_LANGUAGE])


def get_language_list():
    """
    Get a list of all supported languages with their codes and names.
    
    Returns:
        list: List of tuples (code, name)
    """
    return [(code, trans['lang_name']) for code, trans in TRANSLATIONS.items()]
